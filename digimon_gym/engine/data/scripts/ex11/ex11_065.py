        # [Start of Your Main Phase] By trashing 1 [Mineral] or [Rock] trait card from your hand or your Digimon's digivolution cards, gain 1 memory.
        effect0 = ICardEffect()
        effect0.set_effect_name("EX11-065 Trash 1 to gain 1 memory")
