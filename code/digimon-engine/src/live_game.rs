/// Errors surfaced by `LiveGame::from_*` constructors.
#[derive(Debug)]
pub enum LiveGameError {
    /// Deck (or other zone) references card IDs not present in the loaded
    /// `card_data` pool. Listed so callers can suggest a wider pool.
    MissingCards(Vec<String>),
    /// `Game::new` rejected the construction (deck wrong size, etc).
    GameConstruction(String),
    /// Recording-specific failures bubbled up from `ReplayRunner`.
    Replay(ReplayError),
    /// A replay-stepping/scanner method was called on a game not built from
    /// a recording (no bound `ReplayDriver`).
    NotARecording,
}

impl std::fmt::Display for LiveGameError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::MissingCards(ids) => write!(f, "cards not in pool: {:?}", ids),
            Self::GameConstruction(s) => write!(f, "game construction failed: {}", s),
            Self::Replay(e) => write!(f, "replay error: {}", e),
            Self::NotARecording => write!(
                f,
                "this game was not constructed from a recording (no replay log to step)"
            ),
        }
    }
}

impl std::error::Error for LiveGameError {}

impl From<ReplayError> for LiveGameError {
    fn from(e: ReplayError) -> Self {
        // Mirror the `MissingCards` story across error types so tool
        // consumers handle one shape regardless of construction path.
        match e {
            ReplayError::UnknownCard(ids) => LiveGameError::MissingCards(ids),
            other => LiveGameError::Replay(other),
        }
    }
}

/// Result of submitting an action to a `LiveGame`. Mirrors the spec's
/// `ActionResult` shape — never errors out of band, always returns a
/// structured outcome.
#[derive(Debug, Clone, Serialize)]
pub struct ActionResult {
    pub ok: bool,
    pub error: Option<String>,
    /// Events generated by this action, in emission order. Computed
    /// from the engine's monotonic `event_seq` counter (delta before/
    /// after the action). Each entry is a serialized `GameEvent` per
    /// `#[serde(tag = "type")]` — top-level `type` field plus
    /// variant-specific siblings, e.g.
    /// `{"type":"MemoryChange","seq":0,"player":0,"delta":-3,"total":-3}`.
    pub events_emitted: Vec<Value>,
    pub new_phase: String,
    pub pending_selection_after: Option<PendingSelectionDebugView>,
}

