//! Unified live-game surface for debug, smoke-test, and forensic
//! workflows.
//!
//! `LiveGame` wraps a `Game` and exposes:
//! - **Four construction paths**: from decks (with seed), from
//!   hand-specified setup (DebugRunner-style), from a recording, or from
//!   a recording paused at a specific step.
//! - **Compact view accessors**: delegate to the `view::*` types so
//!   tool consumers (CLI, MCP) get token-efficient JSON.
//! - **Action methods**: thin wrappers over the public `Game` action
//!   surface, returning `ActionResult` with `events_emitted` /
//!   `pending_selection_after` so callers don't have to diff state by
//!   hand.
//!
//! The MCP server keeps a `HashMap<GameId, LiveGame>` in memory and
//! routes tool calls into the methods below. The CLI's REPL calls them
//! directly.

