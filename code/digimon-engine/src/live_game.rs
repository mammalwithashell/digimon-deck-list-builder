    #[test]
    fn from_recording_round_trip() {
        let db = minimal_db();
        // Record a tiny game with HeadlessRunner.
        let mut hr = crate::HeadlessRunner::new(
            small_deck(),
            small_deck(),
            &db,
            false,
            true,
            false,
            Some(99),
        )
        .unwrap();
        hr.step(0); // mull keep
        hr.step(0);
        hr.step(62); // pass
        let recording = hr.get_recording().unwrap();

        let lg = LiveGame::from_recording(recording.clone(), &db).expect("from_recording");
        // Step 0 — pre-replay state but post-mulligan reconstruction.
        // Turn 1 already established; recording's first replayable action
        // hasn't been applied yet.
        assert_eq!(lg.game.turn_count, 1);

        // Step ahead to step 1 and confirm the live game advances past the
        // first recorded post-mulligan action.
        let lg2 =
            LiveGame::from_recording_at_step(recording, 1, &db).expect("from_recording_at_step");
        assert!(lg2.game.turn_count >= 1);
    }
