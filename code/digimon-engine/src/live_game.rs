/// Combine a player's hand + deck (from `from_debug`) into a single
/// card_id list. Cards not assigned to a player land in player 0's
/// list by default; the spec for `from_debug` doesn't pin behavior on
/// missing keys.
fn collect_for_player(
    hands: &HashMap<PlayerId, Vec<String>>,
    decks: &HashMap<PlayerId, Vec<String>>,
    player: PlayerId,
) -> Vec<String> {
    let mut ids: Vec<String> = Vec::new();
    if let Some(h) = hands.get(&player) {
        ids.extend(h.iter().cloned());
    }
    if let Some(d) = decks.get(&player) {
        ids.extend(d.iter().cloned());
    }
    ids
}

fn collect_for_player_extended(
    hands: &HashMap<PlayerId, Vec<String>>,
    decks: &HashMap<PlayerId, Vec<String>>,
    securities: &HashMap<PlayerId, Vec<String>>,
    digitamas: &HashMap<PlayerId, Vec<String>>,
    player: PlayerId,
) -> Vec<String> {
    let mut ids = collect_for_player(hands, decks, player);
    if let Some(s) = securities.get(&player) {
        ids.extend(s.iter().cloned());
    }
    if let Some(t) = digitamas.get(&player) {
        ids.extend(t.iter().cloned());
    }
    ids
}

/// Derive `[deck1_ids, deck2_ids]` from a recording's `initial_state`.
/// Concatenates library + hand + security + digitama for each player
/// since those zones together cover the post-shuffle deck (pre-shuffle
/// `deck_list` may be empty on older recordings).
fn deck_ids_from_recording(recording: &Value) -> [Vec<String>; 2] {
    let initial = recording.get("initial_state");
    [
        collect_player_ids_from_recording(initial, "player1"),
        collect_player_ids_from_recording(initial, "player2"),
    ]
}

fn collect_player_ids_from_recording(initial: Option<&Value>, key: &str) -> Vec<String> {
    let Some(p) = initial.and_then(|i| i.get(key)) else {
        return Vec::new();
    };
    // Prefer the pre-shuffle deck_list when present (more authoritative).
    if let Some(arr) = p.get("deck_list").and_then(|v| v.as_array()) {
        let ids: Vec<String> = arr
            .iter()
            .filter_map(|v| v.as_str().map(String::from))
            .collect();
        if !ids.is_empty() {
            return ids;
        }
    }
    // Fallback: union of post-shuffle zones (these together = the deck).
    let mut ids: Vec<String> = Vec::new();
    for zone in &[
        "library_order",
        "initial_hand",
        "security_order",
        "digitama_library_order",
    ] {
        if let Some(arr) = p.get(zone).and_then(|v| v.as_array()) {
            for v in arr {
                if let Some(s) = v.as_str() {
                    ids.push(s.to_string());
                }
            }
        }
    }
    ids
}

/// Spin up a temporary `ReplayRunner` from `recording` and walk every
/// action in the action log, calling `explain_action` *before* each
/// step is applied to capture the action's label in its recording-time
/// engine context. Returns one `Option<String>` per recorded action;
/// mulligan-phase actions (which `ReplayRunner` filters from its
/// step stream) get labels via direct `explain_action` against the
/// fresh post-construction game.
///
/// `total_actions` is the size of the recording's `actions` array;
/// the returned vec has exactly that length.
fn decode_labels_via_replay(
    recording: Value,
    card_data: &HashMap<String, CardData>,
    total_actions: usize,
) -> Vec<Option<String>> {
    let mut labels: Vec<Option<String>> = vec![None; total_actions];

    // We need labels for every recorded action, including the mulligan
    // ones the session filters from its step stream. Construct a fresh
    // ReplaySession (native adapter) — it lands post-mulligan in turn 1.
    let Ok(mut runner) = ReplaySession::new(recording.clone(), card_data, false) else {
        return labels;
    };

    // Mulligan-phase labels are deterministic: action_id 0 = "keep",
    // action_id 1 = "redraw". Decode from the recording's action array
    // directly without needing engine state.
    let Some(actions) = recording.get("actions").and_then(|v| v.as_array()) else {
        return labels;
    };

    // Phase-1: assign labels to mulligan actions.
    for (idx, a) in actions.iter().enumerate() {
        if a.get("phase").and_then(|v| v.as_str()) == Some("Mulligan") {
            let action_id = a.get("action_id").and_then(|v| v.as_u64()).unwrap_or(0);
            labels[idx] = Some(match action_id {
                0 => "mulligan: keep".to_string(),
                1 => "mulligan: redraw".to_string(),
                other => format!("mulligan: unknown ({})", other),
            });
        }
    }

    // Phase-2: walk replayable (non-mulligan) actions, capturing the
    // label BEFORE each step is applied. Map each replayable step back
    // to its original index in `actions`.
    let non_mull_indices: Vec<usize> = actions
        .iter()
        .enumerate()
        .filter(|(_, a)| a.get("phase").and_then(|v| v.as_str()) != Some("Mulligan"))
        .map(|(i, _)| i)
        .collect();
    for (step_idx, orig_idx) in non_mull_indices.iter().enumerate() {
        if step_idx >= runner.total_steps() as usize {
            break;
        }
        let a = &actions[*orig_idx];
        let action_id = a.get("action_id").and_then(|v| v.as_u64()).unwrap_or(0) as u16;
        let recorded_player_py = a.get("player_id").and_then(|v| v.as_u64()).unwrap_or(1) as u8;
        let player_id: PlayerId = recorded_player_py.saturating_sub(1);
        let explanation = explain_action(&runner.game, player_id, action_id);
        labels[*orig_idx] = Some(explanation.label);
        runner.step();
    }

    labels
}

