"""Inventory and stable guidance for legacy card-data command wrappers.

The command names in this module are still referenced by local automation and
documentation.  Keeping their disposition in one typed inventory prevents a
wrapper from silently regaining ownership of a fixed compatibility artifact.
Read-only compatibility modes remain usable; retired mutation modes fail
before fetching or writing. The registry wrapper delegates to the canonical
append-only registry library for checks and explicit scratch projections, but
cannot mutate marker-owned fixed paths.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from enum import StrEnum
from typing import TextIO


DEPRECATION_PREFIX = "DEPRECATED_CARD_DATA_COMMAND"
REFUSAL_PREFIX = "REFUSED_LEGACY_CARD_DATA_WRITE"
CANONICAL_SYNC_GUIDANCE = (
    "stage a complete candidate and use `python -m tools.card_data sync --plan`, "
    "then reviewed `sync --apply`"
)


class LegacyCommandDisposition(StrEnum):
    READ_ONLY_COMPATIBILITY = "read_only_compatibility"
    CANONICAL_DELEGATE = "canonical_delegate"
    RETIRED_MUTATION = "retired_mutation"


@dataclass(frozen=True, slots=True)
class LegacyCommandContract:
    command: str
    accepted_modes: tuple[str, ...]
    refused_modes: tuple[str, ...]
    disposition: LegacyCommandDisposition
    guidance: str


LEGACY_CARD_DATA_COMMANDS = {
    "ingest_cards.py": LegacyCommandContract(
        command="ingest_cards.py",
        accepted_modes=("--preview-set SET",),
        refused_modes=("--set", "--bulk", "--backfill", "SET NAME"),
        disposition=LegacyCommandDisposition.READ_ONLY_COMPATIBILITY,
        guidance=CANONICAL_SYNC_GUIDANCE,
    ),
    "build_card_bundles.py": LegacyCommandContract(
        command="build_card_bundles.py",
        accepted_modes=("--preview --ids ...", "--preview --ids-file FILE"),
        refused_modes=("fixed bundle/card_official write",),
        disposition=LegacyCommandDisposition.READ_ONLY_COMPATIBILITY,
        guidance=CANONICAL_SYNC_GUIDANCE,
    ),
    "scrape_official_evo_costs.py": LegacyCommandContract(
        command="scrape_official_evo_costs.py",
        accepted_modes=("--ids ... to stdout", "--ids-file FILE to stdout"),
        refused_modes=("--out",),
        disposition=LegacyCommandDisposition.READ_ONLY_COMPATIBILITY,
        guidance=(
            "consume stdout for diagnostics; canonical evolution-cost artifacts "
            "are generated by the reviewed card-data revision"
        ),
    ),
    "build_registry.py": LegacyCommandContract(
        command="build_registry.py",
        accepted_modes=(
            "--check",
            "--dry-run",
            "explicit non-fixed scratch outputs",
        ),
        refused_modes=(
            "fixed-path write",
            "--sets",
            "--force",
            "non-default --capacity",
        ),
        disposition=LegacyCommandDisposition.CANONICAL_DELEGATE,
        guidance=(
            "source acquisition and fixed-path publication belong to canonical "
            "sync; this wrapper checks append-only indices and derived "
            "compatibility values or writes explicit scratch paths"
        ),
    ),
}


def legacy_command_contract(command: str) -> LegacyCommandContract:
    try:
        return LEGACY_CARD_DATA_COMMANDS[command]
    except KeyError as exc:
        raise ValueError(f"unknown legacy card-data command: {command}") from exc


def emit_deprecation_warning(
    command: str,
    mode: str,
    *,
    stream: TextIO | None = None,
) -> None:
    contract = legacy_command_contract(command)
    output = stream or sys.stderr
    print(
        f"{DEPRECATION_PREFIX}: {command} {mode} is a compatibility surface; "
        f"{contract.guidance}.",
        file=output,
    )


def refuse_legacy_write(
    command: str,
    mode: str,
    *,
    stream: TextIO | None = None,
) -> int:
    output = stream or sys.stderr
    emit_deprecation_warning(command, mode, stream=output)
    print(
        f"{REFUSAL_PREFIX}: {command} will not mutate fixed card-data artifacts "
        "outside the canonical publication transaction.",
        file=output,
    )
    return 2
