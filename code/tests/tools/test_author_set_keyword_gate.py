def test_real_artifacts_clear_the_reported_false_positives():
    # The task-9.1 cards, read from the committed cards.json + lexicons +
    # manifest: none of them may flag or need a port any more.
    import json

    from data_paths import CARDS_JSON

    rows = json.load(open(CARDS_JSON, encoding="utf-8"))
    cards = {r["card_id"]: r for r in rows} if isinstance(rows, list) else rows
    ids = ["P-238", "LM-047", "P-206", "P-236", "ST22-09", "BT25-075", "BT7-040",
           "BT7-083", "BT13-093", "BT19-090", "BT23-097", "BT22-080", "EX2-039",
           "BT10-056", "P-220", "BT26-078", "EX3-024", "EX5-065", "BT1-039", "AD1-025",
           "BT26-010", "BT26-032", "BT17-078"]
    fields = ("effect_description_eng", "inherited_effect_description_eng",
              "security_effect_description_eng")
    texts = [" ".join(str(cards[c].get(f) or "") for f in fields) for c in ids]
    rep = triage_set_from_artifacts(texts)
    assert not rep.flag_for_human, rep.summary()
    assert not rep.auto_ingest_subsystem and not rep.auto_ingest, rep.summary()
