def test_dsl_lowered_keywords_are_covered():
    # <Delay>, <Use Req.>, <Link +1> / [Link], <Detach>, <Succession>,
    # <Blast DNA Digivolve>, [Assembly] have no `Keyword` enum variant: the
    # engine runs them through DSL vocabulary (the manifest's
    # `dsl_lowered_keywords`). They flagged on every pool that used them.
    rep = triage(
        [
            "[Main] ＜Delay＞ (By trashing this card after the placing turn, ...)",
            "＜Use Req. ([CS] trait)＞ (Specified cards let you ignore color requirements.)",
            "＜Link +1＞ (Add 1 to this Digimon's maximum links.)",
            "Link Requirements [Link] Lv.3 or higher: Cost 2",
            "＜Detach ([Seven Code] trait)＞ (When this Digimon would leave ...)",
            "＜Succession ([Ceresmon])＞ (This Digimon gains all effects other than ＜Succession＞",
            "[Hand] [Counter] ＜Blast DNA Digivolve ([WarGreymon] + [MetalGarurumon])＞",
            "[Assembly] -6 [WarGreymon] x [MetalGarurumon]",
        ],
        card_names=NAMES | {"wargreymon", "metalgarurumon"},
        subsystem_keywords={"link", "blastdnadigivolve"},
        dsl_keywords={"delay", "usereq", "link", "detach", "succession",
                      "blastdnadigivolve", "assembly"},
    )
    assert set(rep.covered) == {"delay", "use req.", "link", "detach", "succession",
                                "blast dna digivolve", "assembly"}
    assert not rep.flag_for_human and not rep.auto_ingest_subsystem and not rep.auto_ingest
    assert not rep.blocks_authoring


def test_dsl_lowered_keyword_beats_the_dcgo_subsystem_class():
    # The DCGO complexity class only matters for a keyword the ENGINE lacks:
    # once the DSL lowers Link it is covered, not a port to schedule (ST22-09
    # blocked Rocks on this).
    rep = triage(["Link Requirements [Link] Lv.3 or higher: Cost 2"],
                 subsystem_keywords={"link"}, dsl_keywords={"link"})
    assert "link" in rep.covered
    assert not rep.auto_ingest_subsystem


