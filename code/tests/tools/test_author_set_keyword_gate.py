def test_names_and_traits_ending_in_a_number_or_parenthetical_resolve_unstripped():
    # Param stripping must not mangle a name/trait before the lexicon lookup:
    # [King Drasil_7D6], [Shoutmon EX6], [Belphemon (X Antibody)],
    # [Eater (Species Form)] are names; [Ver.3] is a trait.
    rep = triage(
        [
            "under a [King Drasil_7D6] in the breeding area",
            "By unsuspending 1 of your [Shoutmon EX6] and 1 of your [ShootingStarmon]",
            "When any of your Digimon digivolve into [Belphemon (X Antibody)], ...",
            "You may place 1 [Eater (Species Form)] from this Digimon's digivolution cards",
            "play 2 level 6 or lower [Composite], [Ver.3] or [Ver.5] Digimon cards",
        ],
        card_names=NAMES | {"king drasil_7d6", "shoutmon ex6", "shootingstarmon",
                            "belphemon (x antibody)", "eater (species form)"},
        traits=TRAITS | {"composite", "ver.3", "ver.5"},
    )
    assert {"king drasil_7d6", "shoutmon ex6", "belphemon (x antibody)",
            "eater (species form)"} <= set(rep.name_hits)
    assert {"ver.3", "ver.5"} <= set(rep.trait_hits)
    assert not rep.flag_for_human


